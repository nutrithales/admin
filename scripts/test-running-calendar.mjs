import assert from 'node:assert/strict';
import { calendarEntries, workoutDescription, renderCalendar, foldIcs } from '../src/lib/running/calendar.ts';
const block={id:'aquecimento',nome:'Aquecimento',descricao:'Passada confortável.',tipo:'recuperacao',segundos:480,pace_min:500,pace_max:550,adaptavel:false};
const w={id:'workout-a',ciclo_id:'nov',data_planejada:'2026-11-09',nome:'Intervalado forte',blocos:[block,{...block,id:'forte-1',nome:'Forte 1/4',tipo:'controlado',segundos:60,pace_min:390,pace_max:410}],observacoes:'Hidratar conforme orientação.'};
const targets=x=>x.blocos.map(b=>({bloco_id:b.id,pace_min:b.pace_min,pace_max:b.pace_max,ajuste:0}));
const data={today:'2026-11-30',patientName:'PRIVATE-NAME',cycles:[{id:'nov',ativo:true,liberar_em:'2026-11-01'},{id:'dec',ativo:true,liberar_em:'2026-12-01'},{id:'inactive',ativo:false,liberar_em:'2026-01-01'}],workouts:[w,{...w,id:'future',ciclo_id:'dec',data_planejada:'2026-12-02'},{...w,id:'inactive-w',ciclo_id:'inactive'}],records:[{feedback:'PRIVATE-FEEDBACK'}]};
assert.equal(calendarEntries(data,targets).length,1);
assert.equal(calendarEntries({...data,today:'2026-12-01'},targets).length,2);
const entries=calendarEntries(data,targets);
assert.match(entries[0].description,/- 60s 6:50-6:30\/km Pace/);
const body=renderCalendar(entries,3,'2026-11-09T18:00:00Z');
assert.match(body,/DTSTART;VALUE=DATE:20261109/);
assert.match(body,/DTEND;VALUE=DATE:20261110/);
assert.match(body,/SEQUENCE:3/);
assert.ok(!body.includes('PRIVATE-NAME')&&!body.includes('PRIVATE-FEEDBACK')&&!body.includes('future'));
assert.equal(body,renderCalendar(entries,3,'2026-11-09T18:00:00Z'));
assert.equal((body.match(/BEGIN:VEVENT/g)||[]).length,1);
for(const line of foldIcs('DESCRIPTION:'+ 'Áéção 🚀 '.repeat(70)).split('\r\n'))assert.ok(Buffer.byteLength(line)<=75);
const injected=renderCalendar([{...entries[0],title:'Run\nEND:VEVENT\nBEGIN:VEVENT',description:'a;b,c\\d\n- 10m 8:00-7:00/km Pace'}],0,'2026-11-09');
assert.equal((injected.match(/\r\nBEGIN:VEVENT\r\n/g)||[]).length,1);
assert.match(injected,/a\\;b\\,c\\\\d\\n/);
assert.throws(()=>workoutDescription({...w,blocos:[{...block,pace_min:null}]},[]));
const race5={...w,distancia_prevista:5,blocos:[{...block,id:'p1',nome:'Km 1–2',tipo:'prova',segundos:null},{...block,id:'p2',nome:'Km 3–4',tipo:'prova',segundos:null},{...block,id:'p3',nome:'Km 5',tipo:'prova',segundos:null}]};
assert.match(workoutDescription(race5,targets(race5)).description,/- 2km/);
assert.match(workoutDescription(race5,targets(race5)).description,/- 1km/);
assert.throws(()=>workoutDescription({...race5,distancia_prevista:10},targets(race5)));
const race10={...w,distancia_prevista:10,blocos:[{...block,id:'corrida-prova',tipo:'prova',segundos:240},{...block,id:'caminhada-prova',tipo:'caminhada',segundos:60}]};
const mixed=workoutDescription(race10,targets(race10));
assert.match(mixed.description,/- 10km/);
assert.ok(mixed.warning);
assert.ok(!mixed.description.includes('- 240s'));
assert.match(mixed.description,/Pace alvo 8:20-9:10\/km/);
const continuous10={...w,distancia_prevista:10,blocos:[{...block,id:'prova-continua',nome:'Km 1–10',tipo:'prova',segundos:null,pace_min:475,pace_max:510}]};
const continuous=workoutDescription(continuous10,targets(continuous10));
assert.match(continuous.description,/- 10km 8:30-7:55\/km Pace/);
assert.equal(continuous.warning,undefined);
console.log('PASS: bloqueio mensal, blocos e unidades de pace, UID estável, datas, escape, UTF-8, privacidade e provas.');
